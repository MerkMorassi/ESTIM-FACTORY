export type WaveformType = 'sine' | 'triangle' | 'asymmetric';

export type ModulationMode = 'continuous' | 'burst' | 'sequenced' | 'sweep';

export interface SignalParameters {
  // Carrier layer (500 Hz - 4000 Hz)
  carrierFreq: number;
  carrierWaveform: WaveformType;
  carrierWaveformB: WaveformType;
  carrierMorph: number; // 0.0 (Waveform A) to 1.0 (Waveform B)
  carrierPhase: number; // 0 to 360 degrees
  
  // Modulation layer (1 Hz - 150 Hz)
  modFreq: number;
  modWaveform: WaveformType;
  modDepth: number; // 0 to 1
  
  // Duty cycle & envelope
  dutyCycle: number; // 10% to 90% (for burst mode)
  burstDurationMs: number; // 10ms to 500ms
  
  // Synchronization click (micro-duration downbeat sync)
  syncClickEnabled: boolean;
  syncClickVol: number; // 0 to 1
  
  // Frequency Sweep parameters
  sweepStartFreq: number;
  sweepEndFreq: number;
  sweepPeriodSec: number;
  
  // Master output
  masterVolume: number; // 0 to 1 (capped at safe -6 dBFS)
  mode: ModulationMode;
  masterBpm: number; // Global BPM (e.g., 60-240)
  syncToMaster: boolean; // Whether to sync sweeps/sequencer to BPM
  
  // Sequencer Loop Range
  seqLoopStart: number;
  seqLoopEnd: number;

  // Nerve Accommodation Mitigation
  jitterAmount: number; // 0 to 1

  // Performance Macro
  performanceMacro: number; // 0 to 1
}

export interface ImpedanceModel {
  nominalResistance: number; // Ohms (e.g., 500 - 3000)
  capacitanceNf: number;      // nF electrode capacitance (e.g., 10 - 100)
  electrodeAreaCm2: number;   // cm² (e.g., 4.0)
}

export interface TelemetryReadout {
  timestamp: number;
  impedanceOhms: number;
  vPeakToPeakVolts: number;
  vRmsVolts: number;
  iPeakMa: number;
  iRmsMa: number;
  chargePerPhaseMicroCoulombs: number;
  powerMw: number;
  carrierFrequencyHz: number;
  modulationFrequencyHz: number;
  dutyCyclePercent: number;
}

export interface SequencerStep {
  active: boolean;
  amplitude: number; // 0.0 to 1.0
  dutyCycle: number; // 0.1 to 0.9
}

export interface TelemetryPreset {
  id: string;
  name: string;
  description: string;
  carrierFreq: number;
  carrierWave: WaveformType;
  modFreq: number;
  modWave: WaveformType;
  modDepth: number;
  mode: ModulationMode;
  dutyCycle: number;
  burstDurationMs: number;
  targetImpedanceOhms: number;
}

export interface DualChannelPreset {
  id: string;
  name: string;
  description: string;
  left: Omit<TelemetryPreset, 'id' | 'name' | 'description'>;
  right: Omit<TelemetryPreset, 'id' | 'name' | 'description'>;
}

export type InterpolationType = 'linear' | 'exponential' | 'step';

export type SegmentType = 'ramp' | 'beat';

export interface BeatStep {
  type: 'none' | 'bass' | 'snare';
}

export interface ProtocolSegment {
  id: string;
  type: SegmentType;
  durationSec: number;
  // Ramp fields
  startIntensity: number;
  endIntensity: number;
  startCarrierFreq: number;
  endCarrierFreq: number;
  startModFreq: number;
  endModFreq: number;
  interpolation: InterpolationType;
  // Beat fields
  bpm?: number;
  steps?: BeatStep[];
  label: string; // e.g., "Excitement", "Plateau"
}

export interface StimulationProtocol {
  id?: string; // Generated by IndexedDB
  name: string;
  description: string;
  totalDurationMs: number;
  lastModified: number;
  masterBpm: number;
  channels: {
    left: ProtocolSegment[];
    right: ProtocolSegment[];
  };
}

export interface BeatTemplate {
  id?: string;
  name: string;
  bpm: number;
  steps: BeatStep[];
  lastModified: number;
}
